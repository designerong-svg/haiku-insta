def build() -> list[dict]:
    life_by_week = build_life_by_week()
    rows: list[dict] = []
    period = "상강"
    for i in range(DAYS):
        d = START + dt.timedelta(days=i)
        if d in TERMS:
            period = TERMS[d]
        evs = sorted(EV.get(d, []), key=lambda e: KIND_ORDER[e["kind"]])
        life = life_by_week[week_no(d)]
        situation = SITUATION[d.weekday()]
        if RAIN[0] <= d <= RAIN[1] and d.weekday() in (2, 6):
            situation = "비 오는 날"
        m = d.month
        season = "spring" if m in (3, 4, 5) else "summer" if m in (6, 7, 8) else "autumn" if m in (9, 10, 11) else "winter"
        main = evs[0] if evs else None
        rows.append({
            "day_no": i + 1,
            "date": d.isoformat(),
            "weekday": WEEKDAY[d.weekday()],
            "week_no": week_no(d),
            "season": season,
            "solar_term_period": period,
            "solar_term_today": TERMS.get(d, ""),
            "seasonal_imagery": TERM_IMAGERY[period],
            "situation": situation,
            "life_stage": life,
            "life_stage_note": LIFE[life][0],
            "event_names": " / ".join(e["name"] for e in evs),
            "event_kinds": " / ".join(dict.fromkeys(e["kind"] for e in evs)),
            "primary_theme": main["theme"] if main else life,
            "tone": main["tone"] if main else LIFE[life][1],
            "inclusion_note": " | ".join(e["note"] for e in evs if e["note"]),
            "source_check": " | ".join(dict.fromkeys(e["check"] for e in evs)),
            "fallback_to_season_ok": (main["fallback"] if main else True),
            "poem_id": None,
            "poem_status": "unassigned",
        })
    return rows


def main() -> None:
    rows = build()
    (ROOT / "data").mkdir(exist_ok=True)
    (ROOT / "data" / "calendar.json").write_text(json.dumps(rows, ensure_ascii=False, indent=1) + "\n", "utf-8")
    heads = {
        "day_no": "일차", "date": "날짜", "weekday": "요일", "week_no": "주차", "season": "계절",
        "solar_term_period": "현재 절기", "solar_term_today": "오늘의 절기", "seasonal_imagery": "계절 이미지",
        "situation": "일상 상황", "life_stage": "인생 시기", "life_stage_note": "인생 시기 설명",
        "event_names": "오늘의 데이·기념일", "event_kinds": "데이 종류", "primary_theme": "오늘의 테마", "tone": "톤",
        "inclusion_note": "공감 포인트/주의", "source_check": "날짜 확인 방식",
        "fallback_to_season_ok": "맞는 시 없으면 계절 시 대체 가능", "poem_id": "배정된 시 ID", "poem_status": "시 배정 상태",
    }
    with (ROOT / "data" / "calendar.csv").open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
