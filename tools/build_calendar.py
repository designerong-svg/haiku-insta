def lunar(y: int, m: int, d: int) -> D:
    c = KoreanLunarCalendar()
    c.setLunarDate(y, m, d, False)
    return D.fromisoformat(c.SolarIsoFormat())


def stem(d: D) -> int:  # 0=갑 … 6=경
    return (d.toordinal() - 730116) % 10


def nth_gyeong(after: D, n: int) -> D:
    d, c = after, 0
    while True:
        if stem(d) == 6:
            c += 1
            if c == n:
                return d
        d += dt.timedelta(days=1)


