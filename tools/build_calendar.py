def week_no(d: D) -> int:
    return (d - START).days // 7 + 1


def build_life_by_week() -> dict[int, str]:
    pins = {week_no(d): t for d, t in PINS.items()}
    out: dict[int, str] = {}
    it = 0
    for w in range(1, week_no(START + dt.timedelta(days=DAYS - 1)) + 1):
        if w in pins:
            out[w] = pins[w]
            continue
        while CYCLE[it % len(CYCLE)] == out.get(w - 1) or CYCLE[it % len(CYCLE)] == pins.get(w + 1):
            it += 1
        out[w] = CYCLE[it % len(CYCLE)]
        it += 1
    return out


